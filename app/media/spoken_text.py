"""소리로 나갈 텍스트를 다듬는다 — 어느 TTS를 쓰든 같은 문제다.

사업자마다 실패하는 방식이 다르다. CLOVA Voice는 괄호 안 내용을 **조용히
버리고**, Polly는 **그대로 읽는다**. 어느 쪽이든 우리가 의도한 소리가 아니다.
LLM이 "(웃음)"이나 "[안내]" 같은 걸 뱉을 때 한쪽에서는 말이 사라지고
다른 쪽에서는 지문이 음성으로 나간다.

그래서 보내기 전에 우리가 먼저 지운다. 그래야 "보낸 것"과 "들린 것"이
같아지고, 벤더를 바꿔도 같은 소리가 난다.
"""

from __future__ import annotations

import re

_BRACKETED = re.compile(r"[(\[{][^)\]}]*[)\]}]")


def strip_unspoken(text: str) -> str:
    """읽히지 않을(또는 읽히면 안 될) 부분을 미리 없앤다.

    괄호 안 내용만 지운다. 문장부호는 억양에 쓰이므로 남긴다 — 과하게
    지우면 진짜 할 말이 사라진다.
    """
    return " ".join(_BRACKETED.sub(" ", text).split())
